// Global language variable — used only by the standalone exported t() and helpers
// (for use outside React components, e.g. utility files, API handlers)
let currentLanguage = 'en';

const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    loadLanguage();
  }, []);

  const loadLanguage = async () => {
    try {
      const savedLanguage = await AsyncStorage.getItem('appLanguage');
      if (savedLanguage === 'en' || savedLanguage === 'te' || savedLanguage === 'hi') {
        setLanguage(savedLanguage);
        currentLanguage = savedLanguage;
      }
    } catch (error) {
      console.error('Error loading language:', error);
    } finally {
      setIsLoading(false);
    }
  };

  const changeLanguage = async (lang) => {
    if (lang === 'en' || lang === 'te' || lang === 'hi') {
      setLanguage(lang);
      currentLanguage = lang;
      await AsyncStorage.setItem('appLanguage', lang);
    }
  };

  // ✅ FIX: t() closes over the React `language` state, not the global `currentLanguage`.
  // This gives t() a new reference on every language change, so useCallback/useMemo
  // consumers (e.g. getQuickActions in HomeScreen) correctly invalidate and rebuild.
  const t = useCallback((key) => {
    return translations[language]?.[key] || translations.en[key] || key;
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, changeLanguage, t, isLoading }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      language: 'en',
      changeLanguage: () => {},
      t: (key) => key,
      isLoading: false,
    };
  }
  return context;
};

// ─── Standalone helpers (for use outside React components) ───────────────────
// These read from the module-level `currentLanguage` which is kept in sync by
// both LanguageProvider.changeLanguage and the exported changeLanguage below.

export const t = (key) => {
  return translations[currentLanguage]?.[key] || translations.en[key] || key;
};

export const changeLanguage = async (lang) => {
  if (lang === 'en' || lang === 'te' || lang === 'hi') {
    currentLanguage = lang;
    await AsyncStorage.setItem('appLanguage', lang);
  }
};

export const getCurrentLanguage = () => currentLanguage;

export const initLanguage = async () => {
  try {
    const savedLanguage = await AsyncStorage.getItem('appLanguage');
    if (savedLanguage === 'en' || savedLanguage === 'te' || savedLanguage === 'hi') {
      currentLanguage = savedLanguage;
    }
  } catch (error) {
    console.error('Error initializing language:', error);
  }
  return currentLanguage;
};